import { build, version } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Deterministic checked-in browser bytes; packed execution never reads TS. */
export async function buildParticleBrowserBundle({
	check = false,
	repoRoot = root,
} = {}) {
	const output = resolve(
		repoRoot,
		"apps/cli/src/programmatic/particle-browser-bundle.generated.ts",
	);
	const result = await build({
		absWorkingDir: resolve(repoRoot),
		entryPoints: ["apps/cli/src/programmatic/particle-browser-entry.ts"],
		bundle: true,
		write: false,
		platform: "browser",
		format: "iife",
		target: "chrome120",
		minify: true,
		legalComments: "none",
		charset: "ascii",
		metafile: true,
		logLevel: "silent",
	});
	if (
		Object.values(result.metafile.outputs).some((value) => value.imports.length)
	)
		throw Error("Particle browser bundle must have no runtime imports");
	const iife = result.outputFiles[0].text;
	const text = `// Generated by script/build-particle-browser.mjs (esbuild ${version}); do not edit.\nexport const PARTICLE_BROWSER_RUNTIME_IIFE = ${JSON.stringify(iife)};\n`;
	if (check) {
		if ((await readFile(output, "utf8")) !== text)
			throw Error(
				"Particle browser bundle is stale; regenerate it before compilation",
			);
	} else await writeFile(output, text, "utf8");
	return {
		output,
		bytes: Buffer.byteLength(iife),
		inputs: Object.keys(result.metafile.inputs).sort(),
	};
}

if (
	process.argv[1] &&
	import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
	if (process.argv.slice(2).some((arg) => arg !== "--check"))
		throw Error("Only --check is supported");
	console.log(
		JSON.stringify(
			await buildParticleBrowserBundle({
				check: process.argv.includes("--check"),
			}),
		),
	);
}
